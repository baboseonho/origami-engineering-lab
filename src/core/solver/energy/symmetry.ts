/**
 * Symmetric subspace of a bar-and-hinge configuration.
 *
 * A model may declare a symmetry group G (model.edu.cyclicSymmetry): each
 * element g is an isometry x ↦ A_g x + t_g of space together with a vertex
 * permutation π_g, such that the reference state, the mesh and the material
 * are invariant: x0_{π_g(v)} = A_g x0_v + t_g. G acts on configurations by
 *
 *     (g·x)_v = A_gᵀ (x_{π_g(v)} − t_g),
 *
 * an affine isometry (A orthogonal, equal vertex masses within an orbit), and
 * x is symmetric iff g·x = x for every g. The orthogonal projection onto that
 * subspace is the group average
 *
 *     P x = (1/|G|) Σ_g g·x                      (orbit average, rotated back)
 *
 * and velocities and forces (vectors, not points) use the linear part only.
 *
 * Why the restriction is honest: the energy V is G-invariant when the targets
 * are, so the force F = −∇V is G-equivariant and F(x) is itself symmetric at a
 * symmetric x (principle of symmetric criticality, Palais 1979). A minimum of
 * V restricted to the symmetric subspace is therefore a TRUE equilibrium of
 * the full model (net force zero on every vertex, not only its symmetric
 * part). What the restriction does decide is WHICH equilibrium: the perfect,
 * imperfection-free structure, which may be unstable to asymmetric
 * (buckling) modes the restriction suppresses.
 */
import type { CyclicSymmetry, OrigamiModel } from '../../topology/types';
import { edgeKey } from '../../topology/build';
import type { TriMesh } from './mesh';

export interface SymElement {
  perm: Int32Array;
  /** row-major orthogonal 3×3 */
  A: Float64Array;
  t: Float64Array;
}

export interface SymmetryGroup {
  elements: SymElement[];
  /** per element: hinge index ↦ image hinge index */
  hingePerm: Int32Array[];
}

const rotZ = (a: number) => [Math.cos(a), -Math.sin(a), 0, Math.sin(a), Math.cos(a), 0, 0, 0, 1];

function compose(g: SymElement, h: SymElement): SymElement {
  // (g∘h)(x) = A_g (A_h x + t_h) + t_g ;  π_{g∘h}(v) = π_g(π_h(v))
  const A = new Float64Array(9), t = new Float64Array(3);
  for (let i = 0; i < 3; i++) {
    for (let j = 0; j < 3; j++) A[3 * i + j] = g.A[3 * i] * h.A[j] + g.A[3 * i + 1] * h.A[3 + j] + g.A[3 * i + 2] * h.A[6 + j];
    t[i] = g.A[3 * i] * h.t[0] + g.A[3 * i + 1] * h.t[1] + g.A[3 * i + 2] * h.t[2] + g.t[i];
  }
  return { perm: Int32Array.from(h.perm, (v) => g.perm[v]), A, t };
}

/**
 * The group generated by the declared symmetry, checked against the model:
 * returns null (symmetric mode unavailable) unless every element maps the
 * reference positions, the bars and the hinges onto themselves.
 */
export function buildSymmetryGroup(model: OrigamiModel, mesh: TriMesh, sym: CyclicSymmetry, tol = 1e-9): SymmetryGroup | null {
  const nV = model.vertices.length;
  const mk = (perm: number[], A: number[], t?: number[]): SymElement | null =>
    perm.length === nV ? { perm: Int32Array.from(perm), A: Float64Array.from(A), t: Float64Array.from(t ?? [0, 0, 0]) } : null;
  const gens = [mk(sym.perm, rotZ((2 * Math.PI) / sym.n)), ...(sym.extra ?? []).map((o) => mk(o.perm, o.A, o.t))];
  if (gens.some((g) => !g)) return null;
  const id = mk(Array.from({ length: nV }, (_, i) => i), [1, 0, 0, 0, 1, 0, 0, 0, 1])!;
  const key = (g: SymElement) => g.perm.join(',');
  const els = new Map<string, SymElement>([[key(id), id]]);
  const queue = [id];
  while (queue.length) {
    const h = queue.shift()!;
    for (const g of gens as SymElement[]) {
      const c = compose(g, h);
      const k = key(c);
      if (els.has(k)) continue;
      if (els.size > 64 * Math.max(1, sym.n)) return null; // not a finite group of the expected size
      els.set(k, c);
      queue.push(c);
    }
  }
  const elements = [...els.values()];
  // validate: reference invariance and a matching permutation of bars and hinges
  const x0 = model.vertices.map((v) => v.referencePosition);
  const scale = Math.max(1e-12, model.scale);
  const barKeys = new Set(mesh.bars.map((b) => edgeKey(b.a, b.b)));
  const hingeOf = new Map(mesh.hinges.map((h, i) => [edgeKey(h.a, h.b), i]));
  const hingePerm: Int32Array[] = [];
  for (const g of elements) {
    for (let v = 0; v < nV; v++) {
      const p = x0[v], q = x0[g.perm[v]];
      for (let i = 0; i < 3; i++) {
        const y = g.A[3 * i] * p[0] + g.A[3 * i + 1] * p[1] + g.A[3 * i + 2] * p[2] + g.t[i];
        if (Math.abs(y - q[i]) > tol * scale) return null;
      }
    }
    for (const b of mesh.bars) if (!barKeys.has(edgeKey(g.perm[b.a], g.perm[b.b]))) return null;
    const hp = new Int32Array(mesh.hinges.length);
    for (let i = 0; i < mesh.hinges.length; i++) {
      const h = mesh.hinges[i];
      const j = hingeOf.get(edgeKey(g.perm[h.a], g.perm[h.b]));
      if (j === undefined || mesh.hinges[j].kind !== h.kind) return null;
      hp[i] = j;
    }
    hingePerm.push(hp);
  }
  return { elements, hingePerm };
}

/** In place: x ← P x (points: affine; vectors with `affine = false`: linear part only). */
export function projectSymmetric(G: SymmetryGroup, x: Float64Array, affine: boolean, tmp: Float64Array = new Float64Array(x.length)): void {
  tmp.fill(0);
  const nV = x.length / 3;
  for (const g of G.elements) {
    const A = g.A, t = g.t;
    for (let v = 0; v < nV; v++) {
      const w = g.perm[v];
      const p0 = x[3 * w] - (affine ? t[0] : 0), p1 = x[3 * w + 1] - (affine ? t[1] : 0), p2 = x[3 * w + 2] - (affine ? t[2] : 0);
      // Aᵀ p
      tmp[3 * v] += A[0] * p0 + A[3] * p1 + A[6] * p2;
      tmp[3 * v + 1] += A[1] * p0 + A[4] * p1 + A[7] * p2;
      tmp[3 * v + 2] += A[2] * p0 + A[5] * p1 + A[8] * p2;
    }
  }
  const k = 1 / G.elements.length;
  for (let i = 0; i < x.length; i++) x[i] = tmp[i] * k;
}

/** max_v,g |(g·x)_v − x_v|: zero exactly for a symmetric configuration. */
export function symmetryError(G: SymmetryGroup, x: Float64Array): number {
  let e = 0;
  const nV = x.length / 3;
  for (const g of G.elements) {
    const A = g.A, t = g.t;
    for (let v = 0; v < nV; v++) {
      const w = g.perm[v];
      const p0 = x[3 * w] - t[0], p1 = x[3 * w + 1] - t[1], p2 = x[3 * w + 2] - t[2];
      e = Math.max(e, Math.hypot(A[0] * p0 + A[3] * p1 + A[6] * p2 - x[3 * v], A[1] * p0 + A[4] * p1 + A[7] * p2 - x[3 * v + 1], A[2] * p0 + A[5] * p1 + A[8] * p2 - x[3 * v + 2]));
    }
  }
  return e;
}

/**
 * Best rigid motion of x onto the reference x0 (Kabsch, equal weights), applied
 * in place. A rigid motion changes no bar length or hinge angle, so it changes
 * no energy; used once, to bring an arbitrarily placed configuration into the
 * symmetry frame before projecting it.
 */
export function alignRigid(x: Float64Array, x0: Float64Array): void {
  const n = x.length / 3;
  const c = [0, 0, 0], c0 = [0, 0, 0];
  for (let v = 0; v < n; v++) for (let i = 0; i < 3; i++) { c[i] += x[3 * v + i] / n; c0[i] += x0[3 * v + i] / n; }
  // H = Σ (x − c)(x0 − c0)ᵀ ; R maximises tr(R H)ᵀ … solved via polar decomposition of H by iteration
  const H = new Float64Array(9);
  for (let v = 0; v < n; v++) for (let i = 0; i < 3; i++) for (let j = 0; j < 3; j++) H[3 * i + j] += (x[3 * v + i] - c[i]) * (x0[3 * v + j] - c0[j]);
  // R = polar factor of Hᵀ (rotation taking x-frame to x0-frame): Newton iteration Q ← ½(Q + Q⁻ᵀ)
  let Q = Float64Array.from([H[0], H[3], H[6], H[1], H[4], H[7], H[2], H[5], H[8]]);
  const det = (M: Float64Array) => M[0] * (M[4] * M[8] - M[5] * M[7]) - M[1] * (M[3] * M[8] - M[5] * M[6]) + M[2] * (M[3] * M[7] - M[4] * M[6]);
  if (!(Math.abs(det(Q)) > 1e-14)) return;
  for (let it = 0; it < 60; it++) {
    const d = det(Q);
    // inverse transpose = cofactor / det
    const C = Float64Array.from([
      Q[4] * Q[8] - Q[5] * Q[7], Q[5] * Q[6] - Q[3] * Q[8], Q[3] * Q[7] - Q[4] * Q[6],
      Q[2] * Q[7] - Q[1] * Q[8], Q[0] * Q[8] - Q[2] * Q[6], Q[1] * Q[6] - Q[0] * Q[7],
      Q[1] * Q[5] - Q[2] * Q[4], Q[2] * Q[3] - Q[0] * Q[5], Q[0] * Q[4] - Q[1] * Q[3],
    ]);
    let diff = 0;
    for (let i = 0; i < 9; i++) { const q = 0.5 * (Q[i] + C[i] / d); diff = Math.max(diff, Math.abs(q - Q[i])); Q[i] = q; }
    if (diff < 1e-15) break;
  }
  if (det(Q) < 0) return; // a reflection is not a rigid motion: leave x as it is
  for (let v = 0; v < n; v++) {
    const p0 = x[3 * v] - c[0], p1 = x[3 * v + 1] - c[1], p2 = x[3 * v + 2] - c[2];
    for (let i = 0; i < 3; i++) x[3 * v + i] = Q[3 * i] * p0 + Q[3 * i + 1] * p1 + Q[3 * i + 2] * p2 + c0[i];
  }
}
